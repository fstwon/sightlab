import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const svgDir = join(root, 'svg');
const files = (await readdir(svgDir)).filter((file) => file.endsWith('.svg')).sort();
const entries = await Promise.all(files.map(async (file) => {
  const name = file.slice(0, -4);
  const svg = (await readFile(join(svgDir, file), 'utf8')).replace(/#[0-9a-f]{6}/gi, 'currentColor');
  return `  '${name}': ${JSON.stringify('data:image/svg+xml,' + encodeURIComponent(svg))},`;
}));
const source = [
  '// AUTO-GENERATED by scripts/generate-icons.mjs. Do not edit manually.',
  'export const iconSources = {', ...entries, '} as const;', '',
  'export type IconName = keyof typeof iconSources;', '',
].join('\n');
await writeFile(join(root, 'src/generated.ts'), source);
